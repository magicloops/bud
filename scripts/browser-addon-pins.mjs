#!/usr/bin/env node
// Generate `bud/src/browser/pins.rs`: the pinned, checksummed artifacts that
// `bud browser prepare` may download (Node runtime and the managed Chrome for
// Testing build). Versions come from the helper's own pins so the daemon,
// helper and browser agree by construction:
//
//   - Node: NODE_VERSION below (must satisfy bud/browser-helper package.json engines)
//   - Chrome for Testing: the build that bud/browser-helper's pinned
//     playwright-core ships in its browsers.json (Playwright installs CfT itself)
//
// Usage:
//   node scripts/browser-addon-pins.mjs            # download+hash, write pins.rs
//   node scripts/browser-addon-pins.mjs --check    # verify pins.rs values match the helper pins (no downloads)
//   node scripts/browser-addon-pins.mjs --no-hash  # write URLs with empty hashes (dev scaffolding)
//
// Every artifact is streamed and SHA-256 hashed; Node hashes are additionally
// cross-checked against nodejs.org SHASUMS256.txt. Nothing is written to disk
// except the generated Rust source.

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const NODE_VERSION = "v24.21.0";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const helperDir = path.join(repoRoot, "bud", "browser-helper");
const outFile = path.join(repoRoot, "bud", "src", "browser", "pins.rs");

// Rust target triple -> Node dist name, CfT platform name.
const TARGETS = [
  { target: "aarch64-apple-darwin", node: "darwin-arm64", cft: "mac-arm64" },
  { target: "x86_64-apple-darwin", node: "darwin-x64", cft: "mac-x64" },
  { target: "x86_64-unknown-linux-gnu", node: "linux-x64", cft: "linux64" },
  { target: "aarch64-unknown-linux-gnu", node: "linux-arm64", cft: "linux-arm64" },
];

function cftExecutable(platform) {
  return platform.startsWith("mac")
    ? `chrome-${platform}/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`
    : `chrome-${platform}/chrome`;
}

export async function readPins() {
  const pkg = JSON.parse(await readFile(path.join(helperDir, "package.json"), "utf8"));
  const playwrightCore = pkg.dependencies["playwright-core"];
  if (!/^\d+\.\d+\.\d+$/.test(playwrightCore)) throw new Error(`playwright-core must be pinned exactly, got ${playwrightCore}`);
  const browsers = JSON.parse(await readFile(path.join(helperDir, "node_modules", "playwright-core", "browsers.json"), "utf8"));
  const chromium = browsers.browsers.find(b => b.name === "chromium");
  if (!chromium?.browserVersion) throw new Error("playwright-core browsers.json has no chromium browserVersion; run npm ci in bud/browser-helper");
  const cftVersion = chromium.browserVersion;
  const minMajor = Number(cftVersion.split(".")[0]);
  return {
    nodeVersion: NODE_VERSION,
    playwrightCore,
    cftVersion,
    minMajor,
    node: TARGETS.map(t => ({
      target: t.target,
      url: `https://nodejs.org/dist/${NODE_VERSION}/node-${NODE_VERSION}-${t.node}.tar.gz`,
      executable: `node-${NODE_VERSION}-${t.node}/bin/node`,
    })),
    // Playwright mirrors Google's builds and is the only source with linux-arm64.
    browser: TARGETS.map(t => ({
      target: t.target,
      url: `https://cdn.playwright.dev/builds/cft/${cftVersion}/${t.cft}/chrome-${t.cft}.zip`,
      executable: cftExecutable(t.cft),
    })),
  };
}

async function streamHash(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const hash = createHash("sha256");
  let size = 0;
  for await (const chunk of response.body) { hash.update(chunk); size += chunk.length; }
  return { sha256: hash.digest("hex"), size };
}

async function nodeShasums(version) {
  const text = await (await fetch(`https://nodejs.org/dist/${version}/SHASUMS256.txt`)).text();
  return new Map(text.trim().split("\n").map(line => { const [sha, name] = line.trim().split(/\s+/); return [name, sha]; }));
}

export function renderPins(pins) {
  const artifact = a => `    Artifact { target: "${a.target}", url: "${a.url}", sha256: "${a.sha256 ?? ""}", size: ${a.size ?? 0}, executable: "${a.executable}" },`;
  return `//! GENERATED by scripts/browser-addon-pins.mjs. Do not edit by hand.
//!
//! Pinned, checksummed downloads for \`bud browser prepare\`. Versions derive
//! from bud/browser-helper (playwright-core pin and its browsers.json), so the
//! daemon, helper and managed browser agree by construction.

/// Managed Node runtime version (nodejs.org dist).
pub const NODE_VERSION: &str = "${pins.nodeVersion}";
/// playwright-core version vendored into the helper.
pub const PLAYWRIGHT_CORE_VERSION: &str = "${pins.playwrightCore}";
/// Chrome for Testing build that playwright-core ${pins.playwrightCore} installs and tests against.
pub const MANAGED_BROWSER_VERSION: &str = "${pins.cftVersion}";
/// Minimum Chromium major accepted for a system browser: Playwright's own.
pub const BROWSER_MIN_MAJOR: u32 = ${pins.minMajor};

pub struct Artifact {
    pub target: &'static str,
    pub url: &'static str,
    pub sha256: &'static str,
    pub size: u64,
    /// Executable path relative to the extraction directory.
    pub executable: &'static str,
}

pub const NODE: &[Artifact] = &[
${pins.node.map(artifact).join("\n")}
];

pub const MANAGED_BROWSER: &[Artifact] = &[
${pins.browser.map(artifact).join("\n")}
];
`;
}

/**
 * Parse the values back out of a generated (and possibly rustfmt-reflowed)
 * pins.rs. Comparing values rather than text keeps `--check` independent of
 * formatting.
 */
export function parsePins(text) {
  const constant = name => {
    const match = text.match(new RegExp(`pub const ${name}: &str = "([^"]*)"`));
    return match?.[1] ?? null;
  };
  const minMajor = text.match(/pub const BROWSER_MIN_MAJOR: u32 = (\d+)/);
  const list = name => {
    const start = text.indexOf(`pub const ${name}: &[Artifact] = &[`);
    if (start === -1) return null;
    const end = text.indexOf("];", start);
    const body = text.slice(start, end);
    const entries = [];
    const entry = /Artifact\s*\{([\s\S]*?)\}/g;
    let m;
    while ((m = entry.exec(body))) {
      const field = key => m[1].match(new RegExp(`${key}:\\s*"([^"]*)"`))?.[1] ?? null;
      const size = m[1].match(/size:\s*(\d+)/);
      entries.push({ target: field("target"), url: field("url"), sha256: field("sha256"), size: size ? Number(size[1]) : null, executable: field("executable") });
    }
    return entries;
  };
  return {
    nodeVersion: constant("NODE_VERSION"),
    playwrightCore: constant("PLAYWRIGHT_CORE_VERSION"),
    cftVersion: constant("MANAGED_BROWSER_VERSION"),
    minMajor: minMajor ? Number(minMajor[1]) : null,
    node: list("NODE"),
    browser: list("MANAGED_BROWSER"),
  };
}

/** Differences between the committed pins and the expected values; empty when current. */
export function pinsDrift(committed, expected) {
  const drift = [];
  for (const key of ["nodeVersion", "playwrightCore", "cftVersion", "minMajor"]) {
    if (committed[key] !== expected[key]) drift.push(`${key}: committed ${committed[key]}, expected ${expected[key]}`);
  }
  for (const list of ["node", "browser"]) {
    const have = committed[list] ?? [];
    for (const want of expected[list]) {
      const got = have.find(a => a.target === want.target);
      if (!got) { drift.push(`${list}: missing target ${want.target}`); continue; }
      if (got.url !== want.url) drift.push(`${list} ${want.target}: url ${got.url} != ${want.url}`);
      if (got.executable !== want.executable) drift.push(`${list} ${want.target}: executable ${got.executable} != ${want.executable}`);
      if (!/^[0-9a-f]{64}$/.test(got.sha256 ?? "")) drift.push(`${list} ${want.target}: sha256 missing or malformed`);
      if (!(got.size > 0)) drift.push(`${list} ${want.target}: size missing`);
    }
  }
  return drift;
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const pins = await readPins();
  if (args.has("--check")) {
    const current = await readFile(outFile, "utf8").catch(() => "");
    const drift = pinsDrift(parsePins(current), pins);
    if (drift.length) { console.error("pins.rs is out of date; run node scripts/browser-addon-pins.mjs\n  " + drift.join("\n  ")); process.exit(1); }
    console.log("pins.rs is current");
    return;
  }
  if (!args.has("--no-hash")) {
    const shasums = await nodeShasums(pins.nodeVersion);
    for (const list of [pins.node, pins.browser]) {
      for (const a of list) {
        process.stderr.write(`hashing ${a.url}\n`);
        Object.assign(a, await streamHash(a.url));
        const published = shasums.get(path.basename(a.url));
        if (published && published !== a.sha256) throw new Error(`${a.url}: SHASUMS256 mismatch`);
      }
    }
  }
  await writeFile(outFile, renderPins(pins));
  // Keep the checked-in file rustfmt-stable so `cargo fmt --check` never fights it.
  const fmt = spawnSync("rustfmt", ["--edition", "2021", outFile], { stdio: "ignore" });
  console.log(`wrote ${path.relative(repoRoot, outFile)}${fmt.status === 0 ? " (rustfmt applied)" : ""}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message ?? error); process.exit(1); });
}
